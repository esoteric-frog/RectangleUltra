#!/usr/bin/env python3
"""Generate Swift Testing @Test wrappers for XCTestCase subclasses in RectangleTests/."""
import re
from pathlib import Path

root = Path(__file__).resolve().parent.parent / "RectangleTests"
cls_re = re.compile(r"^\s*(?:final\s+)?class\s+(\w+)\s*:\s*XCTestCase\b")
fn_re = re.compile(r"^\s*func\s+(test\w*)\s*\(\s*\)\s*(async\s+)?(throws\s+)?(?:\{|$)")
out = ["// GENERATED by scripts/gen_xctest_wrappers.py - do not edit.",
       "import Testing", "import XCTestShim", "@testable import Rectangle", ""]
total = 0
for path in sorted(root.glob("*.swift")):
    if path.name.startswith("_Generated"):
        continue
    current, tests = None, {}
    for line in path.read_text().splitlines():
        if m := cls_re.match(line):
            current = m.group(1); tests[current] = []
        elif current and (m := fn_re.match(line)):
            tests[current].append((m.group(1), bool(m.group(2)), bool(m.group(3))))
    for cls, fns in tests.items():
        if not fns:
            continue
        out.append(f"@Suite(.serialized) struct {cls}_Generated {{")
        for name, is_async, throws in fns:
            call = ("try " if throws else "") + ("await " if is_async else "") + f"$0.{name}()"
            # Both run on the main thread, like XCTest (see XCTestCase.runTest in the shim).
            if is_async:
                out.append(f"    @Test @MainActor func {name}() async throws {{ try await XCTestCase.runAsyncTest({cls}.self) {{ {call} }} }}")
            else:
                # assumeIsolated: the shim runs the body on the main thread; some classes are @MainActor.
                body = ("try " if throws else "") + f"MainActor.assumeIsolated {{ {call.replace('$0', 't')} }}"
                out.append(f"    @Test func {name}() async throws {{ try await XCTestCase.runTest({cls}.self) {{ t in {body} }} }}")
            total += 1
        out.append("}\n")
(root / "_GeneratedTests.swift").write_text("\n".join(out))
print(f"generated {total} tests")
